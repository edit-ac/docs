import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const demand = (condition, message) => { if (!condition) throw Error(message); };
const json = file => JSON.parse(readFileSync(file, 'utf8'));
const parse = (name, text) => ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const publicUrl = path => `/reference-inputs/local-pin-1.3/${path}`;
const code = text => `\n\`\`\`ts\n${text.trim()}\n\`\`\`\n`;

export function declaration(text, symbol, filename = 'input.d.ts') {
  const file = parse(filename, text), [owner, member] = symbol.split('.');
  demand(file.parseDiagnostics.length === 0, `Invalid declaration: ${filename}`);
  const nodes = file.statements.filter(node => node.name?.text === owner ||
    ts.isVariableStatement(node) && node.declarationList.declarations.some(item => item.name.getText(file) === owner));
  demand(nodes.length > 0, `Absent declaration: ${symbol}`);
  const selected = member ? nodes.flatMap(node => node.members ?? []).filter(node => node.name?.getText(file) === member) : nodes;
  demand(selected.length > 0, `Absent public member: ${symbol}`);
  const isPrivate = node => ts.isPrivateIdentifier(node.name ?? {}) || node.modifiers?.some(mod => mod.kind === ts.SyntaxKind.PrivateKeyword || mod.kind === ts.SyntaxKind.ProtectedKeyword);
  demand(!selected.some(isPrivate), `Private declaration: ${symbol}`);
  return selected.map(node => {
    // Copy exact package signatures, excluding implementation-private class members.
    if (!member && ts.isClassDeclaration(node)) {
      const edits = node.members.filter(isPrivate).map(item => [item.getFullStart(), item.end]).reverse();
      let result = node.getText(file), start = node.getStart(file);
      for (const [a, b] of edits) result = result.slice(0, a - start) + result.slice(b - start);
      return result;
    }
    return node.getText(file);
  }).join('\n');
}

export function renderReference(base = root) {
  const manifest = json(resolve(base, 'releases/local-pin-1.3.json'));
  const catalog = json(resolve(base, 'releases/reference-entries.json'));
  demand(manifest.schemaVersion === 1 && catalog.schemaVersion === 1 && catalog.version === manifest.id, 'Unknown reference format/version');
  const inputRoot = resolve(base, 'static/reference-inputs', manifest.id), sources = new Map();
  demand(manifest.inputs.length > 0 && new Set(manifest.inputs.map(i => i.path)).size === manifest.inputs.length, 'Empty/duplicate inputs');
  for (const input of manifest.inputs) {
    demand(/^[a-zA-Z0-9_.-]+(?:\/[a-zA-Z0-9_.-]+)*$/.test(input.path) && !input.path.split('/').includes('..'), 'Unsafe input path');
    const bytes = readFileSync(resolve(inputRoot, input.path));
    demand(digest(bytes) === input.sha256, `Input drift: ${input.path}`);
    sources.set(input.path, bytes.toString());
  }
  const ids = ['lifecycle', 'document', 'commands', 'selection', 'events', 'storage', 'sync', 'extensions'];
  demand(catalog.entries.length === ids.length && ids.every(id => catalog.entries.filter(e => e.id === id).length === 1), 'Missing/duplicate reference family');
  const exports = new Set(parse('index.d.ts', sources.get('web/dist/index.d.ts')).statements.flatMap(node =>
    ts.isExportDeclaration(node) && node.exportClause && ts.isNamedExports(node.exportClause) ? node.exportClause.elements.map(e => e.name.text) : []));
  const evidence = manifest.runtimeEvidence;
  demand(evidence.counts.executed > 0 && evidence.counts.executed === evidence.counts.passed && evidence.counts.failed === 0 && evidence.counts.skipped === 0, 'Unqualified reused receipt');
  const header = (title, weight) => `+++\ntitle = ${JSON.stringify(title)}\nweight = ${weight}\n+++\n\n<!-- Generated by scripts/generate-reference.mjs; edit releases/reference-entries.json. -->\n\n`;
  const outputs = new Map();
  let signatureCount = 0;
  for (const entry of catalog.entries) {
    demand(entry.signatures.length > 0 && entry.contract && entry.errors && entry.limits, `Incomplete contract: ${entry.id}`);
    let page = header(entry.title, entry.weight) + `Version: **0.0.0, unpublished local packed artifact ${manifest.id}**. These are exact declaration excerpts, not installation instructions. Only the linked consumer's named cases have runtime evidence.\n\n`;
    page += `[Qualified local consumer](@/docs/examples/qualified-local.md) · [Core concepts](@/docs/concepts/_index.md) · [Capability profile](@/docs/reference/api-capabilities.md) · [Source manifest](/reference-inputs/local-pin-1.3/manifest.json)\n\n## Parameters and results\n`;
    for (const [file, symbol] of entry.signatures) {
      demand(exports.has(symbol.split('.')[0]), `Not exported from @edit-ac/web: ${symbol}`);
      const path = `web/dist/${file}`;
      demand(sources.has(path), `Missing declaration input: ${path}`);
      page += `\n### ${symbol}\n\n[Complete declaration module](${publicUrl(path)})\n` + code(declaration(sources.get(path), symbol, file));
      signatureCount++;
    }
    page += `\n## Contract and outcomes\n\n${entry.contract}\n\n## Errors and recovery\n\n${entry.errors}\n\n## Prerequisites and platform limits\n\n${entry.limits}\n\n## Version history\n\n2026-10-18: frozen from the PIN-1.3 production tarballs below. Package version 0.0.0 does not identify a registry release; use hashes, not the version alone. Future facade/loading/authoring recipes remain pending exact owner evidence.\n\n`;
    for (const pkg of manifest.packages) page += `- ${pkg.name} ${pkg.version}: \`${pkg.sha256}\` (${pkg.bytes} bytes, unpublished).\n`;
    page += `\n[Full exported names and declaration graph](${publicUrl('web/dist/index.d.ts')})`;
    outputs.set(`content/docs/reference/api-${entry.id}.md`, page + '\n');
  }
  const schema = JSON.parse(sources.get('source/contracts/capabilities.schema.json'));
  demand(schema.properties.contractVersion.const === 1, 'Unknown capability schema');
  const paths = ['source/contracts/profiles/portable-editor-v5.json', 'source/native/ios/capability.json', 'source/native/android/capability.json', 'source/native/desktop/capability.json'];
  let page = header('Pinned capability profiles', 28) + `These are historical reviewed core metadata, not a current release profile or a support promise. The current release-profile producer rejects stale package input hashes; this page deliberately preserves the frozen source states instead. No pending producer is promoted to supported.\n\n[Schema](${publicUrl('source/contracts/capabilities.schema.json')}) · [Profile contract](${publicUrl('source/contracts/profiles/README.md')}) · [Source manifest](/reference-inputs/local-pin-1.3/manifest.json) · [Qualified consumer](@/docs/examples/qualified-local.md) · [Core concepts](@/docs/concepts/_index.md)\n\nAvailable, enabled, authorized and qualified are independent. Imported/static authorization is null; only current host answers can grant it. Resource bounds are admission limits, not performance measurements.\n\n`;
  for (const path of paths) {
    const profile = JSON.parse(sources.get(path));
    demand(profile.contractVersion === 1 && profile.capabilities.length > 0, 'Invalid profile');
    page += `## ${profile.id}\n\n[Original profile](${publicUrl(path)}) · implementation \`${profile.implementation.revision}\`, ${profile.implementation.package} ${profile.implementation.version}, platform ${profile.platform}.\n\n| Version axis | Value |\n|---|---|\n`;
    for (const [key, value] of Object.entries(profile.versions)) page += `| ${key} | ${value} |\n`;
    page += '\n| Capability | Available | Enabled | Authorized | Qualified | Permissions |\n|---|---|---|---|---|---|\n';
    for (const capability of profile.capabilities) {
      demand(capability.state.authorized === null, 'Static profile grants authorization');
      page += `| ${capability.id} | ${capability.state.available} | ${capability.state.enabled} | null | ${capability.state.qualified} | ${capability.permissions.join(', ') || 'none'} |\n`;
    }
    page += `\nResources qualified: **${profile.resources.qualified}**. Converter directions: **${profile.converters.length ? profile.converters.map(c => `${c.from} → ${c.to} (${c.direction}, ${c.fidelity})`).join('; ') : 'none declared'}**. No additional direction, native SDK or resource support is inferred.\n\n`;
  }
  page += '## Version history and recovery\n\nContract version 1 records the exact semantic/sync/descriptor/API/ABI/dialect tuple. Unknown tuples remain inert recoverable bytes; imported claims never authorize editing. Preserve backups and reopen with a compatible implementation. Do not clear documents or silently downgrade schemas. FIT-1.2/1.3 schema/producer tests are historical metadata evidence; PIN-1.3 browser cases qualify only their own packed consumer. See the source manifest for both identities.\n';
  outputs.set('content/docs/reference/api-capabilities.md', page);
  outputs.set('static/reference-inputs/local-pin-1.3/manifest.json', JSON.stringify({ ...manifest, catalogSha256: digest(readFileSync(resolve(base, 'releases/reference-entries.json'))) }, null, 2) + '\n');
  return { outputs, signatureCount, inputCount: manifest.inputs.length, families: ids.length, profiles: paths.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    demand(args.length === 0 || args.length === 1 && args[0] === '--check', 'Expected no arguments or --check');
    const result = renderReference();
    for (const [path, bytes] of result.outputs) {
      const file = resolve(root, path);
      if (args.length) demand(existsSync(file) && readFileSync(file, 'utf8') === bytes, `Generated reference drift: ${path}`);
      else writeFileSync(file, bytes);
    }
    console.log(JSON.stringify({ mode: args.length ? 'check' : 'write', files: result.outputs.size, signatures: result.signatureCount, inputs: result.inputCount, families: result.families, profiles: result.profiles }));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
